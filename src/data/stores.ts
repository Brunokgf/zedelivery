export function haversineDistance(lat1: number, lng1: number, lat2: number, lng2: number) {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((lat1 * Math.PI) / 180) * Math.cos((lat2 * Math.PI) / 180) * Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

export function findNearestStore(lat: number, lng: number) {
  let nearest = STORES[0];
  let minDist = Infinity;
  for (const store of STORES) {
    const d = haversineDistance(lat, lng, store.lat, store.lng);
    if (d < minDist) {
      minDist = d;
      nearest = store;
    }
  }
  return { store: nearest, distance: minDist };
}
